"""Write sql/snowflake/install.sql with causilo_db/core.py inlined into the procedure.

    python scripts/build_snowflake_sql.py

Snowflake runs the procedure's own source; inlining the core means nothing has
to be uploaded to a stage, and causilo-client comes from PyPI through
Snowflake's shared artifact repository. Run this again after changing core.py.
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEAD = """-- Causilo for Snowflake: CALL CAUSILO.PREDICT('SALES.CUSTOMERS', 'CHURN', 'CUSTOMER_ID');
--
-- Generated by scripts/build_snowflake_sql.py from causilo_db/core.py; edit those,
-- not this file.
--
-- A Python stored procedure that reads the table with Snowpark, calls the
-- Causilo API through an external access integration, and returns the
-- predicted rows. The key lives in a Snowflake secret, not in the code.
--
-- Run as a role that can create integrations (ACCOUNTADMIN or one granted it),
-- on a paid account: trial accounts refuse external access integrations.
--
-- The procedure runs with the caller's rights, so it reads only tables the
-- calling role can read; every role granted USAGE on it spends the key in the
-- secret.

CREATE SCHEMA IF NOT EXISTS CAUSILO;

CREATE OR REPLACE NETWORK RULE CAUSILO.CAUSILO_API
  MODE = EGRESS TYPE = HOST_PORT VALUE_LIST = ('api.nums.world');

-- Created once; running this file again keeps the key. To set or change it:
--   ALTER SECRET CAUSILO.API_KEY SET SECRET_STRING = 'csl_...';
CREATE SECRET IF NOT EXISTS CAUSILO.API_KEY
  TYPE = GENERIC_STRING SECRET_STRING = 'csl_...';

CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION CAUSILO_API_ACCESS
  ALLOWED_NETWORK_RULES = (CAUSILO.CAUSILO_API)
  ALLOWED_AUTHENTICATION_SECRETS = (CAUSILO.API_KEY)
  ENABLED = TRUE;

CREATE OR REPLACE PROCEDURE CAUSILO.PREDICT(TBL STRING, TARGET_COLUMN STRING, ID_COLUMN STRING DEFAULT NULL)
  RETURNS TABLE()
  LANGUAGE PYTHON
  RUNTIME_VERSION = '3.11'
  ARTIFACT_REPOSITORY = snowflake.snowpark.pypi_shared_repository
  PACKAGES = ('snowflake-snowpark-python', 'pandas', 'numpy', 'pyarrow', 'requests', 'causilo-client')
  EXTERNAL_ACCESS_INTEGRATIONS = (CAUSILO_API_ACCESS)
  SECRETS = ('key' = CAUSILO.API_KEY)
  HANDLER = 'run'
  EXECUTE AS CALLER
AS $$
"""

TAIL = '''

import _snowflake


def _column(df, name):
    # Snowflake upper-cases unquoted names; accept the name in any case.
    if name is None or name in df.columns:
        return name
    match = [c for c in df.columns if c.upper() == name.upper()]
    if len(match) != 1:
        raise CausiloDBError(f"No column named {name!r}.")
    return match[0]


def run(session, tbl, target_column, id_column=None):
    df = session.table(tbl).to_pandas()
    target_column, id_column = _column(df, target_column), _column(df, id_column)
    check_id_column(id_column, target_column)
    key = _snowflake.get_generic_secret_string("key")
    pred = predict_frame(df, target_column, api_key=key, exclude=[id_column] if id_column else None)
    out = pred.frame
    if id_column:
        out.insert(0, id_column, df[id_column].reset_index(drop=True).iloc[out["row_number"]].to_numpy())
        out = out.drop(columns=["row_number"])
    # Unquoted names in Snowflake are upper case; keep the result easy to query.
    out.columns = [str(c).upper() for c in out.columns]
    return session.create_dataframe(out)
$$;
'''


def core_source() -> str:
    """causilo_db/core.py without its module docstring, ready to sit between $$ marks."""
    core = (ROOT / "causilo_db" / "core.py").read_text()
    tree = ast.parse(core)
    first = tree.body[0]
    if isinstance(first, ast.Expr) and isinstance(getattr(first, "value", None), ast.Constant):
        core = "\n".join(core.splitlines()[first.end_lineno:]).lstrip("\n")
    if "$$" in core:
        raise SystemExit("core.py contains $$, which would end the procedure body")
    return core.rstrip("\n")


def render() -> str:
    """The text of sql/snowflake/install.sql."""
    return HEAD + core_source() + TAIL


def main() -> None:
    out = render()
    (ROOT / "sql" / "snowflake" / "install.sql").write_text(out)
    print(f"wrote sql/snowflake/install.sql ({len(out):,} bytes)")


if __name__ == "__main__":
    main()
