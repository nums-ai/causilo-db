"""Write the Snowflake Native App files with causilo_db/core.py inlined into the procedure.

    python scripts/build_snowflake_app.py

Writes snowflake/native_app/manifest.yml and snowflake/native_app/setup.sql.
snowflake/native_app/README.md is written by hand. The causilo-client source
is not committed: scripts/deploy_snowflake_app.py zips the installed package
with client_zip() and uploads it next to the other files. Run this again after
changing core.py.
"""

from __future__ import annotations

import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_snowflake_sql import ROOT, core_source  # noqa: E402

APP_DIR = ROOT / "snowflake" / "native_app"

# The causilo-client release bundled into the app; deploy refuses any other.
CLIENT_VERSION = "1.0.6"
CLIENT_ZIP = "python/causilo_client.zip"

API_HOST = "api.nums.world"

# The app version follows the package version: 0.2.0 -> V0_2_0.
PACKAGE_VERSION = re.search(r'^version = "([^"]+)"', (ROOT / "pyproject.toml").read_text(), re.M).group(1)
APP_VERSION = "V" + PACKAGE_VERSION.replace(".", "_")

MANIFEST = f"""# Generated by scripts/build_snowflake_app.py; edit that, not this file.
manifest_version: 2

version:
  name: {APP_VERSION}
  label: "causilo-db {PACKAGE_VERSION}"
  comment: "CALL CORE.PREDICT fills the blank cells of a column with Causilo."

artifacts:
  setup_script: setup.sql
  readme: README.md

privileges:
  - CREATE EXTERNAL ACCESS INTEGRATION:
      description: "Creates the integration through which the app reaches the Causilo API at {API_HOST}. It is unusable until you approve the CAUSILO_API specification."
"""

HEAD = f"""-- Causilo Native App setup script.
--
-- Generated by scripts/build_snowflake_app.py from causilo_db/core.py; edit
-- those, not this file.
--
-- The app holds one procedure, CORE.PREDICT, that reads a table the consumer
-- granted to the app, calls the Causilo API at {API_HOST} and returns the
-- predicted rows. The procedure runs with the app's own rights: it can read
-- only what the consumer granted TO APPLICATION. The API key is a sensitive
-- configuration value that an APP_ADMIN sets; it is redacted from query
-- history and never written to a table.

CREATE APPLICATION ROLE IF NOT EXISTS APP_ADMIN;
CREATE APPLICATION ROLE IF NOT EXISTS APP_USER;

-- Egress to the Causilo API. The integration works only after the consumer
-- approves the CAUSILO_API specification.
CREATE SCHEMA IF NOT EXISTS CONFIG;

CREATE OR REPLACE NETWORK RULE CONFIG.CAUSILO_API_RULE
  TYPE = HOST_PORT
  VALUE_LIST = ('{API_HOST}')
  MODE = EGRESS;

-- An integration is an account-level object; the name differs from the one
-- sql/snowflake/install.sql creates, so the two can live in one account.
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION CAUSILO_APP_API_ACCESS
  ALLOWED_NETWORK_RULES = (CONFIG.CAUSILO_API_RULE)
  ENABLED = TRUE;

ALTER APPLICATION SET SPECIFICATION CAUSILO_API
  TYPE = EXTERNAL_ACCESS
  LABEL = 'Causilo API'
  DESCRIPTION = 'Sends the rows to predict, and up to 50,000 filled rows, over HTTPS to the Causilo API.'
  HOST_PORTS = ('{API_HOST}');

-- The consumer's Causilo API key:
--   ALTER APPLICATION <app> SET CONFIGURATION CAUSILO_API_KEY VALUE = 'csl_...';
ALTER APPLICATION SET CONFIGURATION DEFINITION CAUSILO_API_KEY
  TYPE = STRING
  LABEL = 'Causilo API key'
  DESCRIPTION = 'Your Causilo API key (csl_...). Every call of CORE.PREDICT is charged to it.'
  APPLICATION_ROLES = (APP_ADMIN)
  SENSITIVE = TRUE;

-- Imports from the app's own files are allowed only in a versioned schema.
CREATE OR ALTER VERSIONED SCHEMA CORE;
GRANT USAGE ON SCHEMA CORE TO APPLICATION ROLE APP_ADMIN;
GRANT USAGE ON SCHEMA CORE TO APPLICATION ROLE APP_USER;

CREATE OR REPLACE PROCEDURE CORE.PREDICT(TBL STRING, TARGET_COLUMN STRING, ID_COLUMN STRING DEFAULT NULL)
  RETURNS TABLE()
  LANGUAGE PYTHON
  RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python', 'pandas', 'numpy', 'pyarrow', 'requests')
  IMPORTS = ('/{CLIENT_ZIP}')
  EXTERNAL_ACCESS_INTEGRATIONS = (CAUSILO_APP_API_ACCESS)
  HANDLER = 'run'
  EXECUTE AS OWNER
AS $$
"""

TAIL = '''

import causilo_client
from _snowflake import SnowflakeUserException

KEY_SQL = "SELECT SYS_CONTEXT('SNOWFLAKE$APPLICATION', 'GET_CONFIGURATION_VALUE', 'CAUSILO_API_KEY')"


def _column(df, name):
    # Snowflake upper-cases unquoted names; accept the name in any case.
    if name is None or name in df.columns:
        return name
    match = [c for c in df.columns if c.upper() == name.upper()]
    if len(match) != 1:
        raise CausiloDBError(f"No column named {name!r}.")
    return match[0]


def _api_key(session):
    rows = session.sql(KEY_SQL).collect()
    key = rows[0][0] if rows else None
    if not key:
        raise CausiloDBError("No Causilo API key is set. An APP_ADMIN sets it once with "
                             "ALTER APPLICATION <app> SET CONFIGURATION CAUSILO_API_KEY VALUE = 'csl_...';")
    return key


def _predict(session, tbl, target_column, id_column):
    try:
        df = session.table(tbl).to_pandas()
    except Exception as exc:
        raise CausiloDBError(f"Cannot read {tbl!r}. Name it as DATABASE.SCHEMA.TABLE and grant the app "
                             "USAGE on the database and schema and SELECT on the table or view.") from exc
    target_column, id_column = _column(df, target_column), _column(df, id_column)
    check_id_column(id_column, target_column)
    pred = predict_frame(df, target_column, api_key=_api_key(session),
                         exclude=[id_column] if id_column else None)
    out = pred.frame
    if id_column:
        out.insert(0, id_column, df[id_column].reset_index(drop=True).iloc[out["row_number"]].to_numpy())
        out = out.drop(columns=["row_number"])
    # Unquoted names in Snowflake are upper case; keep the result easy to query.
    out.columns = [str(c).upper() for c in out.columns]
    return out


def run(session, tbl, target_column, id_column=None):
    # The app's own code and stack traces stay hidden from the consumer; a
    # SnowflakeUserException shows the consumer only its message.
    try:
        out = _predict(session, tbl, target_column, id_column)
    except (CausiloDBError, causilo_client.CausiloError) as exc:
        raise SnowflakeUserException(str(exc))
    return session.create_dataframe(out)
$$;

GRANT USAGE ON PROCEDURE CORE.PREDICT(STRING, STRING, STRING) TO APPLICATION ROLE APP_ADMIN;
GRANT USAGE ON PROCEDURE CORE.PREDICT(STRING, STRING, STRING) TO APPLICATION ROLE APP_USER;
'''


def render() -> dict[str, str]:
    """The generated files, by path relative to snowflake/native_app/."""
    return {"manifest.yml": MANIFEST, "setup.sql": HEAD + core_source() + TAIL}


def client_zip(dest: Path) -> Path:
    """Zip the installed causilo_client package for the app's stage, the same bytes every time."""
    import causilo_client

    if causilo_client.__version__ != CLIENT_VERSION:
        raise SystemExit(f"causilo-client {causilo_client.__version__} is installed; the app bundles "
                         f"{CLIENT_VERSION}. Install that one, or change CLIENT_VERSION and rebuild.")
    src = Path(causilo_client.__file__).resolve().parent
    dest.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(p for p in src.rglob("*") if p.is_file()):
            if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
                continue
            info = zipfile.ZipInfo(f"causilo_client/{path.relative_to(src).as_posix()}", (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, path.read_bytes())
    return dest


def main() -> None:
    APP_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (APP_DIR / name).write_text(text)
        print(f"wrote snowflake/native_app/{name} ({len(text):,} bytes)")


if __name__ == "__main__":
    main()
